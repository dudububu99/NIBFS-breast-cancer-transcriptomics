def _find_project_dir() -> Path:
    """Find the single project root without assuming a fixed Drive mount name."""
    override = (
        globals().get("PUBLICATION_PROJECT_DIR", None)
        or globals().get("PROJECT_DIR", None)
        or os.environ.get("PUBLICATION_PROJECT_DIR")
    )
    if override:
        p = Path(str(override)).expanduser().resolve()
        if not p.exists():
            raise FileNotFoundError(f"PUBLICATION_PROJECT_DIR tidak ditemukan: {p}")
        return p

    cwd = Path.cwd().resolve()
    if (cwd / "results" / "REPEATED_10X5_K20_LR").is_dir():
        return cwd

    candidates: list[Path] = []
    for script in Path("/content").glob(
        "gdrive*/MyDrive/**/src/repeated_10x5_k20_lr_V2.py"
    ):
        root = script.parents[1]
        if (root / "results" / "REPEATED_10X5_K20_LR").is_dir():
            candidates.append(root.resolve())

    # Broader fallback, still requiring the completed repeated-output directory.
    if not candidates:
        for rep_dir in Path("/content").glob(
            "gdrive*/MyDrive/**/results/REPEATED_10X5_K20_LR"
        ):
            candidates.append(rep_dir.parents[1].resolve())

    unique = sorted(set(candidates), key=lambda p: str(p))
    if len(unique) == 1:
        return unique[0]
    if not unique:
        raise FileNotFoundError(
            "Project tidak ditemukan. Set variabel PUBLICATION_PROJECT_DIR "
            "ke root project sebelum menjalankan script."
        )
    raise RuntimeError(
        "Ditemukan lebih dari satu kandidat project. Set PUBLICATION_PROJECT_DIR.\n"
        + "\n".join(str(p) for p in unique)
    )


def _latest_matching_file(root: Path, patterns: list[str]) -> Path:
    matches: list[Path] = []
    for pattern in patterns:
        matches.extend(p for p in root.rglob(pattern) if p.is_file())
    if not matches:
        raise FileNotFoundError(
            "Tidak ditemukan file untuk pola:\n  - " + "\n  - ".join(patterns)
        )
    return max(matches, key=lambda p: p.stat().st_mtime)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


