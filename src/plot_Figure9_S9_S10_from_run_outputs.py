def _find_frozen_panel(root: Path) -> Path:
    matches = list(root.rglob("final_NIBFS_gene_panel_k20.csv"))
    matches += list(root.rglob("final_top20_NIBFS_gene_panel.csv"))
    matches = [p for p in matches if p.is_file()]
    if not matches:
        raise FileNotFoundError(
            "Frozen top-20 panel tidak ditemukan. Dicari: "
            "final_NIBFS_gene_panel_k20.csv"
        )
    preferred = [
        p for p in matches
        if "runs" in p.parts
        and "results" in p.parts
        and "tables" in p.parts
    ]
    pool = preferred if preferred else matches
    return max(pool, key=lambda p: p.stat().st_mtime)


